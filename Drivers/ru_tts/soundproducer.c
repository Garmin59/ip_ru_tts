/* Local subroutines */

/* Evaluate speech parameters according to the specified stage */
static int16_t eval(icb_t *icb)
{
  int16_t res = (icb->stretch >> 1);
  if (!(--icb->count))
  {
    icb->stretch += icb->delta;
    icb->count = icb->period;
  }
  return res;
}

/*
 * Make a silence of specified length.
 * Returns length.
 */
static uint16_t silence(sink_t *consumer, uint16_t length)
{
  uint16_t i;
  for (i = 0; i < length; i++)
    sink_put(consumer, 0);
  return length;
}

/*
 * Make fading from specified sample index in the voice data.
 * Returns number of generated samples.
 */
static uint16_t fading(sink_t *consumer, const voice_t *voice, uint16_t sidx)
{
  uint16_t i;
  int8_t sample = voice->samples[sidx - 1];
  for (i = 0; i < 3; i++)
  {
    sample >>= 1; // а не происходит ли здесь проблемы из-за логического сдвига вправо вместо арифметического?
    // потому что какие-то "щелчки" я слышу отчётливо!
    // нет, здесь компилятор поставил SAR, уже хлеб.
    sink_put(consumer, sample);

    // но всё равно решение чуть странное - ровно на одном сэмпле остановиться и его ослаблять. Обычно фейдинг - когда по сэмплам идём как обычно, но снижаем громкость...
  }
  return 3;
}

uint8_t CheckParity(uint32_t val, uint32_t mask) // вернёт 0, если чётное, 1, если нечётное
{
  uint8_t res;
  // asm{
  // mov eax, val
  // mov ebx, mask
  // test eax, ebx
  // setpe al
  // mov res, al
  // }
  // return res; //дурацкий код - на чистом ассемблере было бы чуть компактнее, ну да ладно,
  // //лишь бы заработал.
  res = (val & mask) == 0;
  return res;
}

void synthetic8bit(sink_t *consumer, int16_t bx, int16_t cx, int16_t L)
{
  // опытным путём определили - если "случайный шум" будет иметь период всего 255 отсчётов - это нихрена не случайный!
  // гудит только в путь. Так что оставляем 16-битные отсчёты.
  uint16_t x = 205;
  int16_t xcur = 0, xz = 0;          // текущее значение и задержанное на 1 такт
  int16_t ycur = 0, yz = 0, yz2 = 0; // текущее выходное значение, задержанное на 1 такт и на 2 такта
  int16_t bwork, cwork;

  uint16_t k;
  uint8_t shift = cx & 0xFF;        // на сколько дополнительно сдвинуть.
  bwork = (bx + 0x80) >> 8;         // округлили наш коэф.
  cwork = (cx & 0x8000) ? 80 : 100; // это соотв. 0,78125 (100) либо 0,625 (80).

  for (k = 0; k <= L; k++)
  {
    // 0xB8 = 1011 1000.
    if (CheckParity(x, 0x2D))
    {
      x = 0x8000 | (x >> 1);
    }
    else
    {
      x >>= 1;
    }
    // и больше almostWhiteNoise не трогаем, пущай себе сидит до следующей итерации.
    xz = xcur;
    xcur = ((int16_t)x) >> (11 + shift);
    yz2 = yz;
    yz = ycur;
    ycur = xcur + (((yz + yz - xz) * bwork - yz2 * cwork + 0x40) >> 7);

    sink_put(consumer, ycur);
  }
}

// вынесем отдельной процедурой генерацию шипящих "на ходу"
// потому как хотим свой 8-битный вариант.
void syntheticOrig(sink_t *consumer, int16_t bx, int16_t cx, int16_t L)
{
  // опытным путём поняли: это шумы, одни громче, другие тише, чуть разный характер. Один есть глюкавый, 12й из "не тишины", он же последний.
  // он же номер 188
  uint16_t ax = 205;
  int16_t sample_shift = (cx & 0xFF) + 8; // т.е сдвигаем либо на 8, либо на 9, либо на 10 бит вправо (в sink_put). Громкость своего рода, чем больше число - тем тише.
  int16_t var1 = 0;
  int16_t var2 = 0;
  int16_t var3 = 0;
  int k;
  for (k = 0; k <= L; k++)
  {
    int16_t si;
    int16_t tmp = ax & 0x2D; // 0000_0000_0010_1101, выделили только 4 бита, остальные точно нулевые
    tmp ^= tmp >> 4;         // 0000_0000_0000_0010  - т.е один единственный бит может выйти в результате сдвига, по индексу 1 (т.е разряд двоек). После ^ он заведомо установит в единичку этот разряд
    tmp &= 0x0F;             // 0000_0000_0000_1111 - ага, из исходного ax выкусили 4 бита, причём один пихнули в другое место, все сейчас в младших 4.

    // поменяли местами два действия, так он начинает шуметь на всех 16 битах вместо прежних 15.
    ax >>= 1;                   // раз оно беззнаковым обозначено, должен выйти логический сдвиг. Да, так и есть
    if ((0x6996 >> tmp) & 0x01) // 0110_1001_1001_0110. По сути берём из этой последовательности индекс tmp.
    {
      ax |= 0x8000;
    }
    tmp = ax; // тут оно сохраняется, чтобы восстановиться в самом конце цикла. Ну то есть ax как раз шуметь должен, судя по всему, через некий "сдвиговый регистр с обратными связями"

    // и шумит он всегда одинаково, независимо от настроек. Это как раз в последующем коде его немного "подкрашивают".
    //  ((int16_t)ax) >>= 3; //было 2, но мы ж шумелку усилили вдвое!
    ax = (int16_t)ax >> 3;

    // в последующей штуковине мы используем ax, сидящий в диапазоне от 0 до 8191...

    si = (var2 << 1) - var1; // и на первых порах вообще ничего не происходит, они все нули!
    // si = (out[t-1] << 1) - in[t-1] - вход задержанный на 1 такт, но и выход тоже, кстати
    // некая "обратная связь"

    var1 = ax; // единственное присвоение var1, т.е это и есть ax с прошлого такта, но в отличие от исходного ax, тут он в 4 раза меньше.
    // var1 = in[t]

    ax = (uint16_t)((((int32_t)si) * ((int32_t)bx)) >> 15); // ещё множитель к этой "обратной связи" сделали
    // ax = (2out[t-1] - in[t-1])*bx
    ax += var1 - var3; // и теперь рассогласование + текущий сигнал - var3
    // ax = in[t] + (2out[t-1] - in[t-1])*bx - var3

    // или:
    // out[t] = in[t] + (2out[t-1] - in[t-1])*bx - 0.625out[t-2] (либо 0,78125out[t-2] если Ф или Фь)

    var3 = var2; // который является выходным сигналом, задержанным на 2 такта, и дополнительно ослабленным. Выходит, так...
    // var3 = out[t-1], но это сейчас он такой. При переходе на следующую итерацию он станет out[t-2]

    // этот кусок кода, уменьшающий var3 на некоторый коэф., переместили сюда, для понятности.
    var3 >>= 1;        // пока не понимаем: начинается он с нулевого
    var3 += var3 >> 2; // и это ничего не даст, был ноль нулём и останется
    if (cx >= 0)       // у Ф, Фь он отрицательный, у остальных положительный. Из того, что мы уяснили из видюшки, Ф как раз наиболее белый шум. Ш - тяготит к низким частотам, С - к высоким, вроде так.
      var3 += var3 >> 2;
    // в общем, либо var3 = var3/2 + (var3/2)/4 = 5/8*var3 (если это не Ф/Фь) =  0,625var3
    // либо var3 = 5/8*var3 + (5/8(var3))/4 = 5/4*5/8*var3 = 25/32*var3 = 0,78125var3
    // всё это в арифметике со знаком.

    // var3 = out[t-1] * 0,625 либо *0,78125

    var2 = ax;
    sink_put(consumer, (int8_t)(var2 >> sample_shift));
    ax = tmp;
  }
}

/* Global entry point */

/* Generate sound stream and feed it to the specified sink */
void make_sound(soundscript_t *script, sink_t *consumer)
{
  int i;

  sink_put(consumer, 0);
  for (i = 0; (i < script->length) && !consumer->status; i++)
  // да: если при flush либо сбросе части буфера "вовне" тот callback вызывает ошибку (не ноль), это записывается в status и мы прерываем работу.
  {
    int16_t L = script->sounds[i].duration; // НУ ЗАЧЕМ вводить эль малую! Она от единицы почти не отличается, облом тот ещё...
    // извините, я её переименую в заглавную...
    uint16_t j = ((uint16_t)(script->sounds[i].id)) & 0xFF;
    uint16_t k;
    if (j == 7)
      k = 5;
    if (j >= 169)
    {
      /* Fully synthetic sounds that are not voice dependent */
      int16_t bx;
      int16_t cx;
      j -= 169;
      bx = synth_ctrl_data[j][0]; // видно, что здесь чистый дизассемблер из 8086 кода, прям по регистрам шпарим.
      cx = synth_ctrl_data[j][1];
      // всего этих "синтетических звуков" 33 штуки, но из них 21 это {0; -1}, похоже тупо тишина.
      // окромя этого, cx может принимать значения только -1 (тишина), 0, 1, 2, 0x8001 и 0x8002.
      // у bx репертуар поинтереснее: 0, 2 и какие-то большие числа, несколько фиксированных.
      if (cx != -1) // не тишина
      {
        synthetic8bit(consumer, bx, cx, L);
        //                syntheticOrig(consumer, bx, cx, L);
      }
      else
        silence(consumer, L);
    }
    else if (L) /* Non-zero sound length check */
    {
      int16_t ax = 0;
      uint16_t sidx = script->voice->sound_offsets[j];
      uint16_t scnt = script->voice->sound_lengths[j];
      uint8_t stage = script->sounds[i].stage;
      if (scnt > VOICE_THRESHOLD) // т.е более 105. Все гласные - длиной 51 (женский голос) и 101 (мужской), это кстати 200 Гц основной тон если считаем что там 1 период, в женском голосе,
                                  // и 100 Гц основной, если в мужском. Но может там всё ж несколько периодов уместили, ведь считается что голос это от 300 Гц до 3 кГц основная часть, которую сохранить надо.
      // а в действительности такие длинные звуки у нас:
      // основные З,Р,Ж (мягкие и твёрдые), 139(Б,Бэ,Бы,Би), 140 (Д, Дэ,Ды,Ди),
      // 141 (Г,Гэ,Гы,Ги), 142(Б'), 143 (Д')
      // 144 (Г'), 145 (П, Пэ, Пы, Пи), 146 (Т, Тэ, Ты, Ти)
      // 147 (К,Кэ,Кы,Ки), 148 (П'), 149 (Т')
      // 150 (К'), 151 (Ба), 152 (Да)
      // 153 (Га), 154 (Бо, Бу), 155 (До, Ду),
      // 156 (Го,Гу), 157 (Па), 158 (Та),
      // 159 (Ка), 160 (Пу), 161 (Ту),
      // 162 (Ку)
      {
        /* Simply copy prepared pattern from the voice data */
        do
          sink_put(consumer, script->voice->samples[sidx++]);
        while ((--scnt) && (--L));
        // ага: если мы хотели более длинный звук, то хрен нам, он прервётся где прервётся.
      }
      // т.е на них интонация не распространяется (никак их ни повысить, ни понизить нельзя), темп - замедлить не получится (макс. полный звук),
      // убыстрить - да, если обрезать раньше времени. Обрезка здесь без фейда и без кроссфейда, просто "по живому".
      else if (j >= 132) // это у нас согласные, которые совсем согласные (т.е без ВЗРЖЙ, которые можно прозудеть, прорычать, прожужжать)
      // но вообще не так уж часто этот вариант исполняется. Это и не шипящие, и не "длинные" согласные (которые обработаны в прошлом условии).
      // по сути:
      // Л,М,Н (твёрдые и мягкие),
      // и предварительные Б,Д,Г (твёрдые и мягкие), И ВСЁ.
      {
        /* Make a transition of a prepared pattern */
        while (L > ax) // Йода-стиль. Вообще ax < L. Здесь ax - сколько уже записали, L - сколько вообще надо.
        // хотя оно неким странным образом "укорачивается" с двух сторон.
        // тут что-то вроде "замощения" длительности L идущими друг за дружкой периодами,
        // но для повышения тона они будут срезаться на полпути, а для понижения между ними вставляется пауза.
        {
          k = script->icb[stage].stretch; // немного не понимаю. У нас стадий набралось 4 в utterance. 1-"смычка с прошлым звуком", 2-ударение (если надо), 3-основной звук, 4-"смычка со следующим звуком"
                                          // причём для j>=132 будет исключительно stage=2 либо 3.
                                          // будто бы вообще для всех звуков для данной стадии у нас один и тот же k.
          // дело в том, что значение stage поменялось по ходу дела. Теперь каждому звуку (ВФ) из фразы сопоставлено число от 0 до 11.
          do
          {
            sink_put(consumer, script->voice->samples[sidx++]);
            L--;
          } while ((--k) && (--scnt));
          if (k) // т.е сэмпл кончился быстрее, чем мы хотели - в конце просто тишина.
            L -= silence(consumer, k);
          else if (scnt > 1) // мы не хотим весь сэмпл - тогда его попытаемся аккуратно заглушить (хотя я не понимаю такой принцип, и сэмпла всего 3)
            L -= fading(consumer, script->voice, sidx);
          ax = eval(&(script->icb[stage]));
          sidx = script->voice->sound_offsets[j]; // не понимаю, зачем эти строки - ничего ж не поменялось.
          scnt = script->voice->sound_lengths[j];
        }
      }
      else
      {
        /* Mixed and transitional sounds */
        int16_t dx = 0;
        while (L >= ax)
        {
          uint16_t next_pattern_offset;
          k = script->icb[stage].stretch;
          j = ((uint16_t)(script->sounds[i + 1].id)) & 0xFF;
          //                  if (j>168)  //да, попадаем и на шипящие, и на паузы, и тогда ровно один нулевой сэмпл.
          //                    ax = 5;
          next_pattern_offset = script->voice->sound_offsets[j + 1];
          j = script->voice->sound_offsets[j];
          sink_put(consumer, 0);
          ax = (int16_t)(script->voice->samples[j]);
          do
          {
            ax -= (int16_t)(script->voice->samples[sidx]);
            ax = (int16_t)(((int32_t)ax) * ((int32_t)(dx++)) / ((int32_t)L)); // классический кроссфейд. Я б ещё сверху +L/2 добавил, для корректного округления.
            // хотя с этим плохо, оно ж ещё от знака зависит. Но не думаю, что в этом большая проблема.
            ax += (int16_t)(script->voice->samples[sidx++]);
            sink_put(consumer, (int8_t)ax);

            // строчка вроде б и корректная, но когда мы в смотрим, какие сэмплы используются,
            // она нам как бы лишний сэмпл показывает, который здесь получим но не применим!
            // ax = ((++j) < next_pattern_offset) ? ((int16_t)(script->voice->samples[j])) : 0; //если второй сэмпл оказался короче (что вообще-то странно), то вместо него нули будем показывать.
            // поэтому придётся чуть по-другому
            if ((k > 1) && (scnt > 1))
            {
              ax = ((++j) < next_pattern_offset) ? ((int16_t)(script->voice->samples[j])) : 0; // если второй сэмпл оказался короче (что вообще-то странно), то вместо него нули будем показывать.
            }
          } while ((--k) && (--scnt));
          if (k)
            dx += silence(consumer, k);
          else if (scnt > 1)
            dx += fading(consumer, script->voice, sidx);
          ax = dx + eval(&(script->icb[stage]));
          j = ((uint16_t)(script->sounds[i].id)) & 0xFF;
          sidx = script->voice->sound_offsets[j];
          scnt = script->voice->sound_lengths[j];
        }
      }
    }
  }

  /* Flush output buffer */
  sink_flush(consumer);
}
