// Отличие от soundproducer.c - попробуем сделать полноценный ресэмплинг для генерации нужного нам тона,
// вместо отрезания куска ВФ (если надо повысить) или добавления паузы (если надо понизить)

// Обоснование: при настройках "по умолчанию" (pitch=100, speed=100) используется от силы 2/3 ВФ,
// например в женском голосе из 51 сэмпла задействуется 38, а то и 28.
// как итог, голос довольно сильно меняется, добавляются призвуки, вызыванные "обрубанием" (хоть и сколько-нибудь плавным) каждой ВФ.

// Даже если снизить pitch и speed (чтобы потом задать повышенную частоту дискретизации получившегося сигнала), колебания тона довольно велики,
// всяко получается прокрустово ложе.

// Хотя бы для эксперимента, наверное, надо. Впрочем, сейчас попробовал монотонный голос в 50 сэмплов - не звучит. Но может как раз из-за монотонности.

#include <stdint.h>
#include <stdlib.h>

#include "soundscript.h"
#include "voice.h"
#include "sink.h"


/* Local data */

/* Control data used to generate fully synthetic sounds */
// параметры шума. Первое число задаёт его окраску, второе - громкость: -1 просто тишина,
// 0..2 в младшем байте - насколько сдвигать вправо результат дополнительно.
static const int16_t synth_ctrl_data[][2] =
{
  {0, -1},      // 169 - тишина
  {0, -1},      // 170 - тишина
  {0, -1},      // 171 - тишина
  {0, -1},      // 172 - тишина
  {0, -1},      // 173 - тишина
  {0, -1},      // 174 - тишина
  {0, -1},      // 175 - тишина
  {0, -1},      // 176 - тишина
  {0x930C, 0},  // 177 - Ц
  {0x0CF74, 1}, // 178 - Ч
  {2, 0x8002},  // 179 - Ф
  {0x930C, 1},  // 180 - С
  {2, 1},       // 181 - Ш
  {2, 0x8003},  // 182 - Фь
  {0x930C, 0},  // 183 - Сь, такое же в точности как 177
  {0x0CF74, 1}, // 184 - Щ, такое же в точности как 178
  {0x308C, 1},  // 185 - Х, ХЭ, ХЫ, ХИ
  {0x0B8B, 2},  // 186 - Хь
  {0x502E, 1},  // 187 - ХА
  {0x66F0, 1},  // 188 - ХУ, ХО
  {0, -1},      // 189 - тишина
  {0, -1},      // 190 - тишина
  {0, -1},      // 191 - тишина
  {0, -1},      // 192 - тишина
  {0, -1},      // 193 - тишина
  {0, -1},      // 194 - тишина
  {0, -1},      // 195 - тишина
  {0, -1},      // 196 - тишина
  {0, -1},      // 197 - тишина
  {0, -1},      // 198 - тишина
  {0, -1},      // 199 - тишина
  {0, -1},      // 200 - тишина
  {0, -1}       // 201 - тишина
};


// чуть другая функция - подсовывает "ближайшего соседа", чтобы убыстрить или замедлить тон.
// любопытной вариацией был бы стохастический выбор, чтоб сделать голос чуть более "живым".
int8_t resample(const voice_t *voice, int16_t index, int16_t start, int16_t actual_len, int16_t desired_len)
{
  actual_len--;
  desired_len--;
  // index у нас пройдёт от 0 до desired_len-1, по сути.
  // и это должно превратиться в 0 .. actual_len-1.
  index = (index * actual_len + (desired_len >> 1)) / desired_len;
  return voice->samples[start + index];
}

/* Local subroutines */

/* Evaluate speech parameters according to the specified stage */
static int16_t eval(icb_t *icb)
{
  int16_t res = (icb->stretch >> 1);
  if (!(--icb->count))
  {
    icb->stretch += icb->delta;
    icb->count = icb->period;
  }
  return res;
}

/*
 * Make a silence of specified length.
 * Returns length.
 */
static uint16_t silence(sink_t *consumer, uint16_t length)
{
  uint16_t i;
  for (i = 0; i < length; i++)
  {
    sink_put(consumer, 0);
  }
  return length;
}

/*
 * Make fading from specified sample index in the voice data.
 * Returns number of generated samples.
 */
static uint16_t fading(sink_t *consumer, const voice_t *voice, uint16_t sidx)
{
  uint16_t i;
  int8_t sample = (voice->samples)[sidx - 1];
  for (i = 0; i < 3; i++)
  {
    sample >>= 1; // а не происходит ли здесь проблемы из-за логического сдвига вправо вместо арифметического?
    // потому что какие-то "щелчки" я слышу отчётливо!
    // нет, здесь компилятор поставил SAR, уже хлеб.
    sink_put(consumer, sample);

    // но всё равно решение чуть странное - ровно на одном сэмпле остановиться и его ослаблять. Обычно фейдинг - когда по сэмплам идём как обычно, но снижаем громкость...
  }
  return 3;
}

/* Global entry point */

/* Generate sound stream and feed it to the specified sink */
void make_sound(soundscript_t *script, sink_t *consumer)
{
  int i;

  sink_put(consumer, 0);
  for (i = 0; (i < script->length) && !consumer->status; i++)
  // да: если при flush либо сбросе части буфера "вовне" тот callback вызывает ошибку (не ноль), это записывается в status и мы прерываем работу.
  {
    int16_t L = script->sounds[i].duration; // НУ ЗАЧЕМ вводить эль малую! Она от единицы почти не отличается, облом тот ещё...
    // извините, я её переименую в заглавную...
    uint16_t j = ((uint16_t)(script->sounds[i].id)) & 0xFF;
    uint16_t k;
    if (j >= 169)
    {
      /* Fully synthetic sounds that are not voice dependent */
      int16_t noize;
      int16_t vol;
      j -= 169;
      noize = synth_ctrl_data[j][0]; // видно, что здесь чистый дизассемблер из 8086 кода, прям по регистрам шпарим.
      vol = synth_ctrl_data[j][1];
      // всего этих "синтетических звуков" 33 штуки, но из них 21 это {0; -1}, похоже тупо тишина.
      // окромя этого, vol может принимать значения только -1 (тишина), 0, 1, 2, 0x8001 и 0x8002.
      // у noize репертуар поинтереснее: 0, 2 и какие-то большие числа, несколько фиксированных.
      if (vol != -1) // не тишина
      {
        // опытным путём поняли: это шумы, одни громче, другие тише, чуть разный характер. Один есть глюкавый, 12й из "не тишины", он же последний.
        // он же номер 188
        uint16_t noize_data = 205;
        int16_t sample_shift = (vol & 0xFF) + 8; // т.е сдвигаем либо на 8, либо на 9, либо на 10 бит вправо (в sink_put). Громкость своего рода, чем больше число - тем тише.
        int16_t var1 = 0;
        int16_t var2 = 0;
        int16_t var3 = 0;
        for (k = 0; k <= L; k++)
        {
          int16_t si;
          int16_t tmp = noize_data & 0x2D;    // 0000_0000_0010_1101, выделили только 4 бита, остальные точно нулевые
          tmp ^= tmp >> 4;            // 0000_0000_0000_0010  - т.е один единственный бит может выйти в результате сдвига, по индексу 1 (т.е разряд двоек). После ^ он заведомо установит в единичку этот разряд
          tmp &= 0x0F;                // 0000_0000_0000_1111 - ага, из исходного noize_data выкусили 4 бита, причём один пихнули в другое место, все сейчас в младших 4.
          if ((0x6996 >> tmp) & 0x01) // 0110_1001_1001_0110. По сути берём из этой последовательности индекс tmp.
            noize_data |= 0x8000;
          noize_data >>= 1; // раз оно беззнаковым обозначено, должен выйти логический сдвиг. Да, так и есть
          tmp = noize_data; // тут оно сохраняется, чтобы восстановиться в самом конце цикла. Ну то есть noize_data как раз шуметь должен, судя по всему, через некий "сдвиговый регистр с обратными связями"
                    // и шумит он всегда одинаково, независимо от настроек. Это как раз в последующем коде его немного "подкрашивают".
          noize_data >>= 2;

          var3 >>= 1;        // пока не понимаем: начинается он с нулевого
          var3 += var3 >> 2; // и это ничего не даст, был ноль нулём и останется
          if (vol >= 0)       // у Ф, Фь он отрицательный, у остальных положительный.
            var3 += var3 >> 2;
          // в общем, либо var3 = var3/2 + (var3/2)/4 = 5/8*var3 (если это не Ф/Фь) =  0,625var3
          // либо var3 = 5/8*var3 + (5/8(var3))/4 = 5/4*5/8*var3 = 25/32*var3 = 0,78125var3
          // всё это в арифметике со знаком.
          si = var3; // и запомнили "этот твит". Сейчас var3 совсем другому приравняется

          var3 = (var2 << 1) - var1; // и на первых порах вообще ничего не происходит, они все нули!

          var1 = noize_data; // единственное присвоение var1, т.е это и есть noize_data с прошлого такта, но в отличие от исходного noize_data, тут он в 4 раза меньше.

          noize_data = (uint16_t)((((int32_t)var3) * ((int32_t)noize)) >> 15);
          noize_data += var1 - si;

          var3 = var2;

          var2 = noize_data;
          sink_put(consumer, (int8_t)(var2 >> sample_shift));
          noize_data = tmp;
        }
      }
      else
      {
        silence(consumer, L);
      }
    }
    else if (L) /* Non-zero sound length check */
    {
      int16_t counter = 0;
      uint16_t sidx = script->voice->sound_offsets[j];
      uint16_t scnt = script->voice->sound_lengths[j];
      uint8_t stage = script->sounds[i].stage;
      if (scnt > VOICE_THRESHOLD) // т.е более 105. Все гласные - длиной 51 (женский голос) и 101 (мужской), это кстати 200 Гц основной тон если считаем что там 1 период, в женском голосе,
                                  // и 100 Гц основной, если в мужском. Но может там всё ж несколько периодов уместили, ведь считается что голос это от 300 Гц до 3 кГц основная часть, которую сохранить надо.
      // а в действительности такие длинные звуки у нас:
      // основные З,Р,Ж (мягкие и твёрдые), 139(Б,Бэ,Бы,Би), 140 (Д, Дэ,Ды,Ди),
      // 141 (Г,Гэ,Гы,Ги), 142(Б'), 143 (Д')
      // 144 (Г'), 145 (П, Пэ, Пы, Пи), 146 (Т, Тэ, Ты, Ти)
      // 147 (К,Кэ,Кы,Ки), 148 (П'), 149 (Т')
      // 150 (К'), 151 (Ба), 152 (Да)
      // 153 (Га), 154 (Бо, Бу), 155 (До, Ду),
      // 156 (Го,Гу), 157 (Па), 158 (Та),
      // 159 (Ка), 160 (Пу), 161 (Ту),
      // 162 (Ку)
      {
        /* Simply copy prepared pattern from the voice data */
        do
        {
          sink_put (consumer, (script->voice->samples)[sidx++]);
        }
        while ((--scnt) && (--L));
      }
      // т.е на них интонация не распространяется (никак их ни повысить, ни понизить нельзя), темп - замедлить не получится (макс. полный звук),
      // убыстрить - да, если обрезать раньше времени. Обрезка здесь без фейда и без кроссфейда, просто "по живому".
      else if (j >= 132) // это у нас согласные, которые совсем согласные (т.е без ВЗРЖЙ, которые можно прозудеть, прорычать, прожужжать)
      // но вообще не так уж часто этот вариант исполняется. Это и не шипящие, и не "длинные" согласные (которые обработаны в прошлом условии).
      // по сути:
      // Л,М,Н (твёрдые и мягкие),
      // и предварительные Б,Д,Г (твёрдые и мягкие), И ВСЁ.
      {
        /* Make a transition of a prepared pattern */
        while (L > counter) // Йода-стиль. Вообще counter < L. Здесь counter - сколько уже записали, L - сколько вообще надо.
        // хотя оно неким странным образом "укорачивается" с двух сторон.
        // тут что-то вроде "замощения" длительности L идущими друг за дружкой периодами,
        // но для повышения тона они будут срезаться на полпути, а для понижения между ними вставляется пауза.
        // разобрался: в counter заносится половина текущей длительности, для корректного округления. Т.е если "осталось меньше половины" - мы прекращаем
        // а если больше половины - сделаем ещё один период.
        {
          k = script->icb[stage].stretch; // немного не понимаю. У нас стадий набралось 4 в utterance. 1-"смычка с прошлым звуком", 2-ударение (если надо), 3-основной звук, 4-"смычка со следующим звуком"
                                          // причём для j>=132 будет исключительно stage=2 либо 3.
                                          // будто бы вообще для всех звуков для данной стадии у нас один и тот же k.
          // дело в том, что значение stage поменялось по ходу дела. Теперь каждому звуку (ВФ) из фразы сопоставлено число от 0 до 11.
          do
          {
            sink_put(consumer, (script->voice->samples)[sidx++]);
            L--;
          } while ((--k) && (--scnt));
          if (k) // т.е сэмпл кончился быстрее, чем мы хотели - в конце просто тишина.
          {
            L -= silence(consumer, k);
          }
          else if (scnt > 1) // мы не хотим весь сэмпл - тогда его попытаемся аккуратно заглушить (хотя я не понимаю такой принцип, и сэмпла всего 3)
          {
            L -= fading(consumer, script->voice, sidx);
          }
          counter = eval(&(script->icb[stage]));
          sidx = script->voice->sound_offsets[j]; // не понимаю, зачем эти строки - ничего ж не поменялось.
          scnt = script->voice->sound_lengths[j]; // ах да, всё поменялось, тут же sidx++ чтоб идти по сэмплам, и scnt-- чтоб узнать не пора ль заканчивать
        }
      }
      else
      {
        // вот здесь давайте нормально сэмплить...
        /* Mixed and transitional sounds */
        int16_t passed = 0; // сколько сэмплов уже положили
        while (L >= counter)
        {
          //                  uint16_t next_pattern_offset;   //нафиг он нам не сдался, проще тоже начало и длительность
          uint16_t next_pattern_length;
          uint16_t idx; // вот он будет пробегать от 0 до 50 или до 100, или даже того меньше, до stretch в общем.
          int16_t first;
          // но поставили пока uint16, поскольку stretch тоже uint16
          k = script->icb[stage].stretch;
          // итак, хотим длительность одной волны в k сэмплов, но на деле она длится scnt сэмплов.
          // sidx указывает на начало ВФ.

          j = script->sounds[i + 1].id; // не понял хитрую обёртку из &0xFF и (uint16) - у нас id от 0 до 201, зачем вот это вот всё?
          // скорее всего, это был результат дизассемблирования, там брали AL (нижний байт AX) или что-нибудь в этом духе, ну вот перевели "как есть".

          // второй отрезок должен сжаться/растянуться в то же количество раз, а для этого мы просто назначим ту же самую длительность...
          // в конце концов, у нас нет ни одной ВФ короче 51 (для женского голоса) или 101 (для мужского).
          // а только такие у нас здесь и оказываются.

          next_pattern_length = script->voice->sound_lengths[j];
          if (next_pattern_length > scnt)
            next_pattern_length = scnt;
          j = script->voice->sound_offsets[j];
          // по итогу, (sidx, scnt) - параметры первой ВФ, (j,next_pattern_length) - параметры второй ВФ.
          // ещё б сюда переменную одну. По кр. мере для простоты. В дальнейшем оптимизируем, если в этом будет смысл.
          //(если нам звучание понравится)
          for (idx = 0; idx < k; idx++)
          {
            counter = resample(script->voice, idx, j, scnt, k);       // второй звук
            first = resample(script->voice, idx, sidx, scnt, k); // первый звук.
            counter -= first;
            counter = (int16_t)(((int32_t)counter) * ((int32_t)(passed++)) / ((int32_t)L));
            counter += first;
            sink_put(consumer, (int8_t)counter);
          }

          counter = passed + eval(&(script->icb[stage]));
          // при таком подходе мы не трогаем ни sidx, ни scnt, так что обновлять их и не будем...
        }
      }
    }
  }

  /* Flush output buffer */
  sink_flush(consumer);
}
