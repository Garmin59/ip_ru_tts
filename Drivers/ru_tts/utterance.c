#include <stdint.h>
#include <stdlib.h>

#include "soundscript.h"
#include "transcription.h"

/* Local data */
// дополнительные озвучания для безударных гласных, после каждой из согласных.
static const uint8_t soundset1[] =
{
  0, 0, 0, 0, 5, 5, // В,З,Р,Ж,Й,Вь
  5, 5, 0, 0, 0, 5, // Зь,Рь,Л,М,Н,Ль
  5, 5, 0, 0, 0, 5, // Мь,Нь,Б,Д,Г,Бь
  5, 5, 0, 0, 0, 5, // Дь,Гь,П,Т,К,Пь,
  5, 5, 0, 5, 0, 0, // Ть,Кь,Ц,Ч,Ф,С,
  0, 5, 5, 5, 0, 5  // Ш,Фь,Сь,Щ,Х,Хь
};
// используется для Й, Вь, Зь, Рь, Ль, Мь, Нь, Бь, Дь, Гь, Пь, Ть, Кь, Ч, Фь, Сь, Щ, Хь.
// в общем, не мудрствуя лукаво, в этом массиве пятёрками отмечены все мягкие согласные. Для них два варианта,
// для твёрдых достаточно одного.

// гласные звуки. Как видоизменяется в зависимости от предыдущего согласного (их 36 разных)
static const uint8_t soundset2[] =
{
  10, 20, 20, 20, 70, 50, // В,З,Р,Ж,Й,Вь
  60, 60, 40, 10, 20, 80, // Зь,Рь,Л,М,Н,Ль
  50, 60, 10, 20, 30, 50, // Мь,Нь,Б,Д,Г,Бь
  60, 70, 10, 20, 30, 50, // Дь,Гь,П,Т,К,Пь,
  60, 70, 20, 60, 10, 20, // Ть,Кь,Ц,Ч,Ф,С,
  20, 50, 60, 60, 30, 70  // Ш,Фь,Сь,Щ,Х,Хь
};
// итого В,М,Б,П,Ф:   +10
// З,Р,Ж,Н,Д,Т,С,Ш:   +20
// Г,К,Х:             +30
// Л:                 +40
// Вь,Мь,Бь,Пь,Фь:    +50
// Зь,Рь,Нь,Дь,Ть,Сь: +60
// Й, Гь, Кь, Хь:     +70
// Ль:                +80

// Б(20),Д(21),Г(22) (твёрдые), за которыми следует гласная
// П(26),Т(27),К(28) (твёрдые)
static const uint8_t soundset3[] =
{
  134, // БУ (154), ДУ (155), ГУ (156), ПУ (160), ТУ (161), КУ (162)
  134, // БО (154), ДО (155), ГО (156), ПО (160), ТО (161), КО (162)
  131, // БА (151), ДА (152), ГА (153), ПА (157), ТА (158), КА (159)
  119, // БЭ (139), ДЭ (140), ГЭ (141), ПЭ (145), ТЭ (146), КЭ (147)
  119, // БЫ (139), ДЫ (140), ГЫ (141), ПЫ (145), ТЫ (146), КЫ (147)
  119  // БИ (139), ДИ (140), ГИ (141), ПИ (145), ТИ (146), КИ (147)
};

// это Х+гласная
static const uint8_t soundset4[] =
{
  148,      // ХУ, в итоге 188
  148,      // ХО, в итоге 188
  147,      // ХА, в итоге 187
  145, 145, // ХЭ, ХЫ в итоге 185
  145       // ХИ, в итоге 185
};

/* Local subroutines */

/* Put specified sound into the soundscript */
static void put_sound(soundscript_t *script, uint8_t sound, uint8_t stage)
{
  script->sounds[script->length].id = sound;
  script->sounds[script->length++].stage = stage;
}

/* Global functions */

/* Build utterance according to phonetic transcription */
void build_utterance(uint8_t *transcription, soundscript_t *script)
{
  uint16_t i = TRANSCRIPTION_START;
  uint8_t a = 43;
  uint8_t c = transcription[i];

  while ((a < 44) && (i < TRANSCRIPTION_BUFFER_SIZE))
  {
    uint8_t flags = 0;
    uint16_t j;

    for (j = i; j < TRANSCRIPTION_BUFFER_SIZE; j++)
    {
      if (transcription[j] != 43) // т.е весь этот внешний цикл - это пропустить все 43 (паузы между словами)
      {
        if (transcription[j] < 43) // и пропустив их, мы хотим найти звук, гласный или согласный
        {
          for (j++; j < TRANSCRIPTION_BUFFER_SIZE; j++)
          {
            if (transcription[j] > 42) // и тогда проматываем, пока не найдём всё-таки паузу. Интересно, что пауза через # здесь не учитывается
            {
              if ((transcription[j] == 53) || (transcription[j] == 54)) // вот она, ударная или безударная. НЕ ТАК: основное либо дополнительное ударение!
              {
                flags |= 2;                                             // выходит, флаг 2 это когда после гласной делается небольшая пауза?
              }
              break;
            }
          }
        }
        break;
      }
    }

    while (i < TRANSCRIPTION_BUFFER_SIZE)
    {
      uint8_t b = a;
      a = c;
      if (a > 43)
      {
        break;
      }
      flags &= ~1;

      while (i < TRANSCRIPTION_BUFFER_SIZE)
      {
        c = transcription[++i];
        if (c < 53)
        {
          break;
        }
        flags |= 1;
      }

      if (a == 43)
      {
        put_sound(script, 190, 2); // тишина (что и понятно, 43 это у нас разделитель, его даже назвали breakpoint в intonation
        break;
      }
      else if (a > 5) // то есть, согласные и всяческие паузы
      {
        if (a > 13) // и не ВЗРЖЙ (чем они так интересны?)
        {
          if (a > 19) // и не ЛМН (мягкие и твёрдые)
          {
            if (a > 31) // и не БДГПТК (мягкие и твёрдые)
            {
              if (a > 41)                  // и вообще не буквы
              {
                put_sound(script, 189, 2); // тоже тишина
              }
              else if (a < 34)
              {                                // т.е a либо 32, либо 33, никак иначе, это у нас Ц,Ч.
                put_sound(script, a + 143, 2); // 175 или 176 - тишина
                put_sound(script, a + 145, 3); // 177 или 178, Ц или Ч
              }
              else if ((a < 40) || (a == 41) || (c > 5))
              {
                // т.е либо 34..39 (Ф,С,Ш, Фь, Сь, Щ), либо 41 (Хь). Либо если 34..41 (всякое шипящее), когда следующая согласная
                put_sound(script, a + 145, 2);
              }
              // выходит 179 = Ф
              // 180 = С
              // 181 = Ш
              // 182 = Фь
              // 183 = Сь
              // 184 = Щ
              // 185 = Х
              // 186 = Хь
              else
              {
                put_sound(script, a + soundset4[c], 2); // остались только 40 (Х), 42 (?) и только если следующая гласная.
              }
              // и тут
            }
            else                             // именно что БДГПТК (мягкие и твёрдые)
            {                                // индексы 20..31
              put_sound(script, a + 143, 2); // т.е звуки 163..174. Причём для П,Т,К, мягких и твёрдых, это звуки тишины!
              if (a < 29)                    // исключили Пь, Ть, Кь
              {
                if (a < 26) // исключили П,Т,К
                {
                  if ((a < 23) && (c < 6)) // Б(20),Д(21),Г(22) (твёрдые), за которыми следует гласная
                  {
                    put_sound(script, a + soundset3[c], 3);
                  }
                  else // остались только Бь(23), Дь(24), Гь(25)
                       // либо Б,Д,Г, но перед согласной
                  {
                    put_sound(script, a + 119, 3); // ВФ 142, 143, 144
                                                   // либо 139, 140, 141
                  }
                } // if (a < 26)
                else if (c < 6) // П(26),Т(27),К(28) (твёрдые), за которыми следует гласная
                {
                  put_sound(script, a + soundset3[c], 3);
                }
                else                             // П,Т,К, но перед согласной
                {
                  put_sound(script, a + 119, 3); // ВФ 145, 146, 147
                }
              } // if (a < 29)
              else
              {
                put_sound(script, a + 119, 3); // Пь, Ть, Кь, ВФ 148, 149, 150
              }
            } // if (a > 31) {..} else {..}
          } // if (a > 19)
          else                             // остаётся Л(14), М(15), Н(16) (мягкие и твёрдые, мягкие +3)
          {
            put_sound(script, a + 119, 2); // ВФ 133 (Л), 134(М), 135(Н), 136(Ль), 137(Мь), 138(Нь)
          }
        }
        else // остались ВЗРЖЙ (6..13) - согласные, которые почти что гласные, их можно тянуть (зудеть, жужжать, рычать)
        {
          if (b > 13)                     // а вот b - это предыдущий звук, похоже. Если он - "совсем согласный" (не гласный и не эти ВЗРЖЙ):
          {
            put_sound(script, a + 99, 1); // выходит ВФ от 105 до 112
          }
          if ((a != 10) || (transcription[i + 1] > 52) || ((c > 5) && (c < 44)))
          {
            put_sound(script, a + 117, 2);  // выходит ВФ от 123..130
            if (c > 13)                     // если ещё и следующая согласная ("совсем согласная")
            {
              put_sound(script, a + 99, 3); // то повторяем снова тот же трюк, с ВФ от 105 до 112
            }
          }
          else                         // особые случаи: звук Й, либо за ним следует короткая пауза внутри слова (53, 54), либо следующий звук согласный либо конец слова
          {
            put_sound(script, 122, 2); // это иногда в дополнение к основному
          }
        }
      }
      else // остаются гласные
      {
        j = 90;
        if (b > 5) // предыдущий звук не был гласным
        {
          if (b < 42)             // был конкретно согласным
          {
            j = soundset2[b - 6]; // выбираем прибавочку (по десяткам), для каждого из 36 согласных звуков своя
          }
          if (a == 5)             // И превращаем в Ы, конкретно для этого переходного звука?
          {
            j--;
          }
          // по сути вот здесь можно было бы в else поставить j=90, т.е предыдущий звук это пауза.
        }
        else                      // звук был гласным
        {
          j = (a != 5) ? 95 : 99; // свои правила для И (a==5) и для всех остальных
        }
        put_sound(script, a + j, 1);
        // flag|=2 означает что в слове в принципе проставлено ударение.
        // т.е если мы просто не заморочались его ставить, то флаг будет 0 или 1, и условие всегда выполнено.
        // иными словами, любые гласные будут интерпретироваться как ударные!
        // а вот если ударение проставлено, но при этом ровно за этой гласной нет паузы, указывающей на него (53 или 54),
        // вот тогда будет flag=2, и одну ВФ мы пропустим.
        // и наконец, если ударение проставлено и оно на текущей гласной, то flag=3 и мы добавляем эту ВФ.
        if (flags != 2)
        {
          if ((b > 5) && (b < 42)) // и перед ней стоит согласная
          {
            j = soundset1[b - 6]; // прибавит 5 для мягких согласных
            if (a == 5)           //"И" превращаем в "Ы"
              j--;
          }
          else
            j = (a != 5) ? 0 : 4;      // если перед ней гласная, то они прям самыми первыми 5 звуками записаны (0..4), тогда как И (5) становится 9.
          put_sound(script, a + j, 2); // выходит, уже вторая ВФ закладывается?
          // 0..4 для гласных после твёрдой согласной (причём И такая же как Ы), либо после гласной (но не И)
          // 9 для И после гласной
          // 5..9 для гласных после мягкой согласной.
        }
        if ((b > 5) && (b < 42)) // в любом случае (ударная или нет), если после согласной идёт - ещё одну ВФ пишем
          put_sound(script, a + soundset1[b - 6] + ((a != 5) ? 95 : 94), 3);
        // для твёрдых согласных и гласных кроме И, это будет 95..99, И здесь "превратится в Ы" (т.е также 99)
        // для мягких согласных, 100..104.
        else
        {
          put_sound(script, a + ((a != 5) ? 95 : 99), 3);
        }
        // для гласной после другой гласной или самой первой, будет 95..99 для всех кроме И.
        // для И будет 99+5 = 104. Выходит, одиночная И такая же как Ы после мягких согласных? Оригинально...
        if (c > 5) // после нашей гласной идёт согласная или паузы
        {
          if (c != 42) // 42-пауза, обозначенная # (до конца не знаю, как это работает)
          {
            if (c == 43) // обычная пауза (пробел)
            {
              j = transcription[i + 1]; // а что за ним?
              if (j > 5)                // согласная или другая пауза
              {
                if (j < 42) // всё же согласная
                  put_sound(script, a + soundset2[j - 6] + ((a != 5) ? 5 : 4), 4);
                // как на самом первом этапе, но со сдвигом на 5
                else
                  put_sound(script, a + ((a != 5) ? 90 : 89), 4); // пауза
                // а тут занимаем 90..94 (на первом этапе было 95..99 и 104)
              }
              else if (b > 5)
                put_sound(script, a + ((a != 5) ? 95 : 99), 4);
              // бред какой-то, зачем-то вспомнили предыдущую фонему.
              // склоняюсь к тому, что либо ошибка в дизассемблировании, либо ошибка в исходном драндулете
            }
            else if (c > 43) // другие паузы (запятая, точка с запятой, и даже маленькие паузы-ударения)
              put_sound(script, a + ((a != 5) ? 90 : 89), 4);
            else // всё же согласная идёт после нас
              put_sound(script, a + soundset2[c - 6] + ((a != 5) ? 5 : 4), 4);
          }
          else
            put_sound(script, a + ((a != 5) ? 90 : 89), 4); //
        }
        else if (b > 5)
        {
          put_sound(script, a + ((a != 5) ? 95 : 99), 4);
        }
      }
    }
  }

  if (i >= TRANSCRIPTION_BUFFER_SIZE)
  {
    a = 44;
  }
  put_sound(script, a + 147, 2);
}
